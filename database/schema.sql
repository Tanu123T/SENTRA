-- SENTRA canonical PostgreSQL/PostGIS schema.
-- Apply this file to sentra_db. It is intentionally non-destructive.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE SCHEMA IF NOT EXISTS sentra;

CREATE TABLE IF NOT EXISTS sentra.wards (
    ward_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_name VARCHAR(100) NOT NULL,
    population INTEGER,
    area_sq_km NUMERIC(10, 2),
    geometry geometry(MULTIPOLYGON, 4326),
    CONSTRAINT wards_population_nonnegative CHECK (population IS NULL OR population >= 0),
    CONSTRAINT wards_area_nonnegative CHECK (area_sq_km IS NULL OR area_sq_km >= 0)
);

CREATE TABLE IF NOT EXISTS sentra.weather_observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_id INTEGER NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    rainfall_mm NUMERIC(10, 2),
    temperature_c NUMERIC(6, 2),
    humidity_percent NUMERIC(5, 2),
    CONSTRAINT weather_observations_ward_fk
        FOREIGN KEY (ward_id) REFERENCES sentra.wards (ward_id) ON DELETE RESTRICT,
    CONSTRAINT weather_observations_rainfall_nonnegative
        CHECK (rainfall_mm IS NULL OR rainfall_mm >= 0),
    CONSTRAINT weather_observations_humidity_range
        CHECK (humidity_percent IS NULL OR humidity_percent BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS sentra.risk_assessments (
    risk_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_id INTEGER NOT NULL,
    assessed_at TIMESTAMPTZ NOT NULL,
    risk_score NUMERIC(5, 2) NOT NULL,
    risk_level VARCHAR(20) NOT NULL,
    model_version VARCHAR(50),
    CONSTRAINT risk_assessments_ward_fk
        FOREIGN KEY (ward_id) REFERENCES sentra.wards (ward_id) ON DELETE RESTRICT,
    CONSTRAINT risk_assessments_score_range
        CHECK (risk_score BETWEEN 0 AND 100),
    CONSTRAINT risk_assessments_level_valid
        CHECK (risk_level IN ('LOW', 'MODERATE', 'HIGH', 'CRITICAL'))
);

CREATE TABLE IF NOT EXISTS sentra.population_exposure (
    exposure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_id INTEGER NOT NULL,
    assessed_at TIMESTAMPTZ NOT NULL,
    population_exposed INTEGER NOT NULL,
    exposure_percent NUMERIC(5, 2),
    severity VARCHAR(20),
    CONSTRAINT population_exposure_ward_fk
        FOREIGN KEY (ward_id) REFERENCES sentra.wards (ward_id) ON DELETE RESTRICT,
    CONSTRAINT population_exposure_count_nonnegative
        CHECK (population_exposed >= 0),
    CONSTRAINT population_exposure_percent_range
        CHECK (exposure_percent IS NULL OR exposure_percent BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS sentra.resources (
    resource_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_type VARCHAR(30) NOT NULL,
    resource_name VARCHAR(150) NOT NULL,
    capacity INTEGER NOT NULL,
    available_units INTEGER NOT NULL,
    location geometry(POINT, 4326),
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT resources_type_valid
        CHECK (resource_type IN ('AMBULANCE', 'BED', 'SHELTER')),
    CONSTRAINT resources_capacity_nonnegative
        CHECK (capacity >= 0),
    CONSTRAINT resources_available_nonnegative
        CHECK (available_units >= 0),
    CONSTRAINT resources_available_within_capacity
        CHECK (available_units <= capacity),
    CONSTRAINT resources_status_valid
        CHECK (status IN ('AVAILABLE', 'BUSY', 'OFFLINE'))
);

CREATE TABLE IF NOT EXISTS sentra.resource_allocations (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT NOT NULL,
    ward_id INTEGER NOT NULL,
    allocated_at TIMESTAMPTZ NOT NULL,
    quantity INTEGER NOT NULL,
    priority_score NUMERIC(5, 2),
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED',
    CONSTRAINT resource_allocations_resource_fk
        FOREIGN KEY (resource_id) REFERENCES sentra.resources (resource_id) ON DELETE RESTRICT,
    CONSTRAINT resource_allocations_ward_fk
        FOREIGN KEY (ward_id) REFERENCES sentra.wards (ward_id) ON DELETE RESTRICT,
    CONSTRAINT resource_allocations_quantity_positive
        CHECK (quantity > 0),
    CONSTRAINT resource_allocations_priority_range
        CHECK (priority_score IS NULL OR priority_score BETWEEN 0 AND 100),
    CONSTRAINT resource_allocations_status_valid
        CHECK (status IN ('PLANNED', 'ACTIVE', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE IF NOT EXISTS sentra.simulations (
    simulation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    simulation_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    scenario_type VARCHAR(50) NOT NULL,
    parameters JSONB NOT NULL DEFAULT '{}'::jsonb,
    status VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    description TEXT,
    CONSTRAINT simulations_scenario_type_valid
        CHECK (scenario_type IN ('RAINFALL', 'RESOURCE', 'DEMAND')),
    CONSTRAINT simulations_status_valid
        CHECK (status IN ('CREATED', 'RUNNING', 'COMPLETED', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS wards_geometry_gist_idx
    ON sentra.wards USING GIST (geometry);

CREATE INDEX IF NOT EXISTS weather_observations_ward_idx
    ON sentra.weather_observations (ward_id);
CREATE INDEX IF NOT EXISTS weather_observations_observed_at_idx
    ON sentra.weather_observations (observed_at);
CREATE INDEX IF NOT EXISTS weather_observations_ward_observed_at_idx
    ON sentra.weather_observations (ward_id, observed_at);

CREATE INDEX IF NOT EXISTS risk_assessments_ward_idx
    ON sentra.risk_assessments (ward_id);
CREATE INDEX IF NOT EXISTS risk_assessments_assessed_at_idx
    ON sentra.risk_assessments (assessed_at);
CREATE INDEX IF NOT EXISTS risk_assessments_ward_assessed_at_idx
    ON sentra.risk_assessments (ward_id, assessed_at);

CREATE INDEX IF NOT EXISTS population_exposure_ward_idx
    ON sentra.population_exposure (ward_id);
CREATE INDEX IF NOT EXISTS population_exposure_assessed_at_idx
    ON sentra.population_exposure (assessed_at);
CREATE INDEX IF NOT EXISTS population_exposure_ward_assessed_at_idx
    ON sentra.population_exposure (ward_id, assessed_at);

CREATE INDEX IF NOT EXISTS resources_location_gist_idx
    ON sentra.resources USING GIST (location);

CREATE INDEX IF NOT EXISTS resource_allocations_resource_idx
    ON sentra.resource_allocations (resource_id);
CREATE INDEX IF NOT EXISTS resource_allocations_ward_idx
    ON sentra.resource_allocations (ward_id);
CREATE INDEX IF NOT EXISTS resource_allocations_allocated_at_idx
    ON sentra.resource_allocations (allocated_at);
